# Шаблон идеального симметричного сердца (8 столбцов)
HEART_LINES = [
    f"{BR}❤️❤️{BR}{BR}❤️❤️{BR}",
    f"🧡🧡🧡🧡🧡🧡🧡🧡",
    f"💛💛💛💛💛💛💛💛",
    f"💚💚💚💚💚💚💚💚",
    f"{BR}💙💙💙💙💙💙{BR}",
    f"{BR}{BR}💜💜💜💜{BR}{BR}",
    f"{BR}{BR}{BR}💖💖{BR}{BR}{BR}"
]

def render_name_emoji(name: str, count: int = None, color_shift: int = 0) -> str:
    """
    Рендерит имя из разноцветных сердечек с использованием невидимых отступов.
    • Буквы идеально ровные и прямые.
    • Для коротких имен (до 3 символов) рисует в одну строчку.
    • Для длинных имен группирует по 2 буквы в ряд, чтобы текст не ломался ни на каких телефонах.
    """
    clean_chars = [c.upper() for c in name if c.isalnum() or c in ("!", "?", "-")]
    if not clean_chars:
        clean_chars = [c.upper() for c in name.strip()]
    if count is not None:
        clean_chars = clean_chars[:count]
    if not clean_chars:
        return ""

    chunk_size = 3 if len(clean_chars) == 3 else 2
    chunks = [clean_chars[i:i + chunk_size] for i in range(0, len(clean_chars), chunk_size)]

    blocks = []
    global_letter_idx = 0

    for chunk in chunks:
        row_lines = ["", "", "", "", ""]
        for c in chunk:
            grid = FONT_4x5.get(c, ["1111", "1001", "1111", "1001", "1001"])
            color = HEART_COLORS[(global_letter_idx + color_shift) % len(HEART_COLORS)]
            global_letter_idx += 1
            for r in range(5):
                line_str = "".join(color if b == '1' else BR for b in grid[r])
                if row_lines[r]:
                    row_lines[r] += BR  # 1 невидимый символ между буквами в строке
                row_lines[r] += line_str
        blocks.append("\n".join(row_lines))

    return "\n\n".join(blocks)

@core.command("love", description="Emoji heart and typewriter colorful name animator", usage=f"{CMD_PREFIX}love [имя]")
async def love_cmd(event: events.NewMessage.Event):
    """
    Анимация из сердечек в стиле typewriter (.type):
    • .love — рисует идеальное разноцветное сердце
    • .love <имя> — вырисовывает имя из разноцветных сердечек буква за буквой
    • .love в ответ на сообщение — берет имя пользователя и рисует его
    """
    raw = event.raw_text or getattr(event, "text", "") or ""
    args = raw.split(maxsplit=1)
    name_arg = args[1].strip() if len(args) > 1 else ""

    # Если имя не передано аргументом, проверяем реплай
    if not name_arg:
        try:
            reply = await event.get_reply_message()
            if reply:
                sender = await reply.get_sender()
                if sender:
                    name_arg = (getattr(sender, "first_name", "") or getattr(sender, "title", "") or "").strip()
        except Exception:
            pass

    # ==========================================
    # РЕЖИМ 1: ПРОСТО .love (РИСУЕТ СЕРДЦЕ)
    # ==========================================
    if not name_arg:
        # Построчное появление сердца (эффект пишущей машинки)
        for row in range(1, len(HEART_LINES) + 1):
            frame = "\n".join(HEART_LINES[:row])
            try:
                await event.edit(frame)
                await asyncio.sleep(0.18)
            except Exception:
                await asyncio.sleep(0.2)

        # Небольшая цветовая волна для вау-эффекта
        colors = ["❤️", "🧡", "💛", "💚", "💙", "💜", "💖"]
        for shift in range(1, 4):
            shifted_lines = []
            for r_idx, line in enumerate(HEART_LINES):
                old_color = colors[r_idx % len(colors)]
                new_color = colors[(r_idx + shift) % len(colors)]
                shifted_lines.append(line.replace(old_color, new_color))
            try:
                await event.edit("\n".join(shifted_lines))
                await asyncio.sleep(0.2)
            except Exception:
                pass

        # Финал
        final_text = "\n".join(HEART_LINES) + "\n\n       **I love you** ❤️✨"
        try:
            await event.edit(final_text)
        except Exception:
            pass
        return

    # ==========================================
    # РЕЖИМ 2: .love <ИМЯ> (ИМЯ ИЗ СЕРДЕЧЕК)
    # ==========================================
    display_name = name_arg.strip().capitalize()
    clean_chars = [c for c in name_arg if c.isalnum() or c in ("!", "?", "-")]
    if not clean_chars:
        clean_chars = list(name_arg.strip())

    total_letters = len(clean_chars)

    # Анимация: посимвольное появление букв, как в .type
    for count in range(1, total_letters + 1):
        frame = render_name_emoji(name_arg, count=count)
        try:
            await event.edit(frame)
            await asyncio.sleep(0.22)
        except Exception:
            await asyncio.sleep(0.25)

    # Финальный перелив цветов и романтическая подпись
    final_render = render_name_emoji(name_arg, count=total_letters, color_shift=1)
    final_message = f"{final_render}\n\n💖 **Я люблю тебя, {display_name}!** 💖✨"

    try:
        await event.edit(final_message)
    except Exception:
        pass
